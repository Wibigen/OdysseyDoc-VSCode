import * as vscode from "vscode";
import * as fs from "fs";
import * as path from "path";
import { CompileEntry, parseGccIncludeDirs, shellSplit, transformEntry } from "./core/compdb";
import { baseFramework, buildDir, ensureBase, getExecEnv, projectRoot, runCapture } from "./env";
import { BuildRunner } from "./build";
import { DocState } from "./state";

const CLANGD_EXT = "llvm-vs-code-extensions.vscode-clangd";

function waitBuild(runner: BuildRunner): Promise<boolean> {
    return new Promise((resolve) => {
        const d = runner.onBuildDone((r) => {
            d.dispose();
            resolve(r.ok);
        });
    });
}

const DOT_CLANGD_MARK = "# Generated by the OdysseyDoc extension";

function writeDotClangd(file: string) {
    const db = "CompilationDatabase: .vscode/odysseydoc-clangd";
    let txt = "";
    try {
        txt = fs.readFileSync(file, "utf8");
    } catch {
        /* absent */
    }
    if (!txt || txt.startsWith(DOT_CLANGD_MARK)) {
        fs.writeFileSync(
            file,
            [
                DOT_CLANGD_MARK,
                "CompileFlags:",
                `  ${db}`,
                "  Add: [-Wno-invalid-offsetof, -Wno-unused-private-field, -Wno-c++11-narrowing]",
                "Diagnostics:",
                "  UnusedIncludes: None",
                "  MissingIncludes: None",
                "",
            ].join("\n"),
        );
        return;
    }
    if (txt.includes("CompilationDatabase")) {
        fs.writeFileSync(file, txt.replace(/CompilationDatabase:.*$/m, db));
    } else if (/^CompileFlags:\s*$/m.test(txt)) {
        fs.writeFileSync(file, txt.replace(/^CompileFlags:\s*$/m, `CompileFlags:\n  ${db}`));
    } else {
        fs.writeFileSync(file, `CompileFlags:\n  ${db}\n---\n` + txt);
    }
}

export async function setupClangd(st: DocState, runner: BuildRunner, silent = false): Promise<boolean> {
    const root = silent ? projectRoot() : await ensureBase("to configure clangd");
    if (!root) return false;
    const env = getExecEnv(root);
    const ccHost = path.join(buildDir(root), "compile_commands.json");
    if (!fs.existsSync(ccHost)) {
        if (silent) return false;
        const go = await vscode.window.showInformationMessage(
            `build/compile_commands.json does not exist yet: CMake has to be configured once (${baseFramework(root) === "hakkun" ? "cmake -S . -B build" : "make configure"}).`,
            "Configure now",
            "Cancel",
        );
        if (go !== "Configure now") return false;
        const p = waitBuild(runner);
        await runner.run("configure");
        if (!(await p) || !fs.existsSync(ccHost)) {
            vscode.window.showErrorMessage("CMake configuration failed: check the OdysseyDoc terminal.");
            return false;
        }
    }

    return await vscode.window.withProgress({ location: vscode.ProgressLocation.Notification, title: "OdysseyDoc: configuring clangd" }, async (progress) => {
        const entries = JSON.parse(fs.readFileSync(ccHost, "utf8")) as CompileEntry[];
        if (!entries.length) throw new Error("compile_commands.json is empty");
        const first = entries[0].arguments ?? shellSplit(entries[0].command ?? "");
        const compiler = first[0];
        // Hakkun builds with clang: its compile_commands only need the path mapping
        const native = baseFramework(root) === "hakkun" || /clang/.test(compiler);
        let gccDirs: string[] = [];
        if (!native) {
            progress.report({ message: "reading devkitA64 include folders…" });
            const r = await runCapture(`${compiler.includes(" ") ? `'${compiler}'` : compiler} -xc++ -std=gnu++23 -E -v - </dev/null 2>&1`, env, root.fsPath, undefined, 30000);
            gccDirs = parseGccIncludeDirs(r.out + "\n" + r.err);
            if (!gccDirs.length) st.log(`clangd: could not read the system include folders of ${compiler}:\n${r.out}${r.err}`);
        }

        progress.report({ message: `converting ${entries.length} entries…` });
        const mapPath = (p: string) => env.mapper.toHost(p);
        const out = entries.map((e) =>
            transformEntry(e, {
                mapPath,
                gccIncludes: gccDirs,
                native,
                readFile: (p) => {
                    try {
                        return fs.readFileSync(p, "utf8");
                    } catch {
                        return undefined;
                    }
                },
            }),
        );
        const outDir = path.join(root.fsPath, ".vscode", "odysseydoc-clangd");
        fs.mkdirSync(outDir, { recursive: true });
        fs.writeFileSync(path.join(outDir, "compile_commands.json"), JSON.stringify(out, null, 1));

        // .clangd: tells clangd where the converted database is (works without touching settings)
        writeDotClangd(path.join(root.fsPath, ".clangd"));

        // extension clangd
        if (!vscode.extensions.getExtension(CLANGD_EXT)) {
            const ans = await vscode.window.showInformationMessage("The clangd extension is not installed. Install it now?", "Install clangd", "Later");
            if (ans === "Install clangd") await vscode.commands.executeCommand("workbench.extensions.installExtension", CLANGD_EXT);
        }

        // the mod's .cpp can be anywhere: clangd must know where the compilation database is
        const scopePick = await vscode.window.showQuickPick(
            [
                { label: "$(globe) All my C++ files", description: "user setting: works for a .cpp anywhere (recommended)", t: vscode.ConfigurationTarget.Global },
                ...(vscode.workspace.workspaceFolders?.length
                    ? [{ label: "$(folder) Only the open folder", description: "workspace setting", t: vscode.ConfigurationTarget.Workspace }]
                    : []),
            ],
            { title: "Apply the OdysseyDoc clangd configuration to…" },
        );
        const target = scopePick?.t ?? vscode.ConfigurationTarget.Global;
        let settingsOk = false;
        try {
            const conf = vscode.workspace.getConfiguration("clangd");
            const args = (conf.get<string[]>("arguments") ?? []).filter((x) => !x.startsWith("--compile-commands-dir") && !x.startsWith("--query-driver"));
            args.push(`--compile-commands-dir=${outDir}`);
            if (!args.some((x) => x.startsWith("--header-insertion"))) args.push("--header-insertion=never");
            await conf.update("arguments", args, target);
            settingsOk = true;
        } catch (e) {
            st.log(`clangd: settings not changed (${e})`);
        }

        const cpptools = vscode.extensions.getExtension("ms-vscode.cpptools");
        if (cpptools) {
            const cc = vscode.workspace.getConfiguration("C_Cpp");
            if (cc.get<string>("intelliSenseEngine") !== "disabled") {
                const ans = await vscode.window.showInformationMessage(
                    "The Microsoft C/C++ extension is installed: its IntelliSense conflicts with clangd. Disable it?",
                    "Disable Microsoft IntelliSense",
                    "Keep it",
                );
                if (ans === "Disable Microsoft IntelliSense") await cc.update("intelliSenseEngine", "disabled", target);
            }
        }
        try {
            await vscode.commands.executeCommand("clangd.restart");
        } catch {
            /* clangd not active yet */
        }
        if (!settingsOk) {
            vscode.window.showWarningMessage("clangd is not loaded yet: reload the window, then run \"OdysseyDoc: Set up code completion (clangd)\" again so it also works outside the base.");
        }

        vscode.window.showInformationMessage(
            `clangd configured from the base (${out.length} file(s)): code completion works for your .cpp files, wherever they are. ${native || gccDirs.length ? "" : "⚠ devkitA64 system headers not found (see the OdysseyDoc output)."}`,
        );
        st.log(`clangd: compile_commands converted → ${outDir} (system folders: ${gccDirs.join(", ") || "none"})`);
        return true;
    });
}
